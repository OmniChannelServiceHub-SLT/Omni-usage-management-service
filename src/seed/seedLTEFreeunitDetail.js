async function seed() {
  await mongoose.connect(process.env.MONGODB_URI);

  let spec = await UsageSpecification.findOne({ name: 'LTEFreeunitDetail' });
  if (!spec) {
    spec = await UsageSpecification.create({
      name: 'LTEFreeunitDetail',
      description: 'Free unit details for an LTE subscriber',
    });
  }

  await Usage.deleteMany({ usageType: 'LTEFreeunitDetail', 'relatedParty.id': LTE_NUMBER });

  const usage = await Usage.create({
    usageDate: new Date(),
    usageType: 'LTEFreeunitDetail',
    status: 'recorded',
    usageSpecification: { id: spec.id, name: spec.name },
    relatedParty: [{ '@referredType': 'Subscriber', id: LTE_NUMBER }],
    usageCharacteristic: [
      { name: 'freeUnitCount', value: listofFreeUnit.length },
    ],
    mysltResponse,
  });

  console.log(`[SEED] LTEFreeunitDetail spec: ${spec.id}`);
  console.log(`[SEED] LTEFreeunitDetail usage for ${LTE_NUMBER} (${listofFreeUnit.length} free units): ${usage.id}`);

  await mongoose.disconnect();
}

seed().catch((err) => {
  console.error('[SEED] Failed:', err.message);
  process.exit(1);
});